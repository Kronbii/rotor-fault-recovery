"""Write ``sitl/config/x500.yaml`` from PX4's Gazebo model files and airframe defaults.

    .venv/bin/python sitl/make_airframe.py

Reads (never modifies) ``Tools/simulation/gz/models/x500_base/model.sdf`` (links, mass,
inertia), ``.../x500/model.sdf`` (motor plugins), ``Tools/simulation/gz/worlds/default.sdf``
(gravity) and the SITL airframe ``ROMFS/px4fmu_common/init.d-posix/airframes/4001_gz_x500``
(``SIM_GZ_EC_MIN/MAX``: the map from PX4's normalised motor command to the rotor-speed
command sent to Gazebo).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from harness import PX4_DIR  # noqa: E402
from rotorfault.airframe import Airframe, from_gazebo_sdf  # noqa: E402


def px4_default(name: str, airframe_file: Path) -> float:
    m = re.search(rf"param set-default {name}\s+(\S+)", airframe_file.read_text())
    if not m:
        raise KeyError(name)
    return float(m.group(1))


def main():
    gz = PX4_DIR / "Tools" / "simulation" / "gz"
    world = (gz / "worlds" / "default.sdf").read_text()
    g = abs(float(re.search(r"<gravity>\s*\S+\s+\S+\s+(\S+)\s*</gravity>", world).group(1)))
    af = from_gazebo_sdf(gz / "models/x500_base/model.sdf", gz / "models/x500/model.sdf", g)
    afile = PX4_DIR / "ROMFS/px4fmu_common/init.d-posix/airframes/4001_gz_x500"
    w0 = px4_default("SIM_GZ_EC_MIN1", afile)
    w1 = px4_default("SIM_GZ_EC_MAX1", afile)
    d = af.to_dict()
    d["motor"]["speed_at_zero"] = w0
    d["motor"]["speed_at_full"] = w1
    d["motor"]["delay_s"] = 0.0
    d["log"] = {
        "format": "px4-ulog",
        "motor_order": "PX4 motors 1-4: front-right, rear-left, front-left, rear-right",
    }
    rev = subprocess.run(
        ["git", "-C", str(PX4_DIR), "describe", "--tags", "--always"],
        capture_output=True,
        text=True,
    ).stdout.strip()
    d["source"] = (
        f"{af.source}; PX4-Autopilot {rev}; command map SIM_GZ_EC_MIN/MAX = {w0:g}/{w1:g} "
        f"rad/s from airframe 4001_gz_x500; gravity {g:g} m/s^2 from worlds/default.sdf. "
        "delay_s is identified on the fault-free calibration flights (sitl/analyze.py)."
    )
    out = HERE / "config" / "x500.yaml"
    Airframe.from_dict(d).to_yaml(
        out,
        header="# PX4 x500 (Gazebo Harmonic SITL) for the rotorfault diagnoser.\n"
        "# Generated by sitl/make_airframe.py -- do not edit by hand.",
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
